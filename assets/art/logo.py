                                        # todas as linhas tem o mesmo tamanho
    x = (LARGURA_BORDA - largura_logo) // 2 + 1       # ela pega a largura da borda
    y = 3
    for i, texto in enumerate(LOGO_BALATRO):
        W.gotoxy(x, y + i)
        escrever(texto)
